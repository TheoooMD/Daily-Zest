function computeSaaS(S) {
  const pct = k => S[k] / 100;

  // 1. Capacité commerciale & pipe
  const maxDemosMo = S.sales_reps * S.demos_per_rep;
  const leadsMo = S.leads_per_month;
  const servedRatio = leadsMo > 0 ? Math.min(1, maxDemosMo / leadsMo) : 1;
  const actualDemosMo = leadsMo * servedRatio;
  const lostLeadsMo = leadsMo * (1 - servedRatio);
  const newCustMo = actualDemosMo * pct('close_rate');
  const newCustYr = newCustMo * 12;

  // 2. Churn & expansion
  const churnRate = pct('logo_churn');
  const expRate = pct('expansion_rate');
  const GRR = Math.max(0, 1 - churnRate) * 100;
  const NRR = Math.max(0, 1 - churnRate + expRate) * 100;

  // 3. Tarification Hybride & ACV
  const seatDiscount = 1 - pct('annual_discount') * pct('upfront_pct');
  const seatRevPerCustYr = S.avg_seats * S.seat_price * 12 * seatDiscount;
  const tokenRevPerCustYr = S.token_usage_cust * S.token_price * 12;
  const ACV = seatRevPerCustYr + tokenRevPerCustYr;

  // 4. Revenus & Facturation (Billings vs GAAP)
  const customers = S.cust;
  const ARR = customers * ACV;
  const MRR = ARR / 12;
  const g = pct('growth');
  const billingsGrowthAdj = 1 + pct('upfront_pct') * (g / 2);
  const Billings = ARR * billingsGrowthAdj;
  const GAAP_Revenue = ARR;

  // Deferred Revenue au passif
  const deferredRevRatio = pct('upfront_pct') * 0.5;
  const DeferredRevenue = Billings * deferredRevRatio;

  // 5. Coûts directs (COGS)
  const gpuInferenceCost = customers * S.token_usage_cust * S.gpu_cost_per_m * 12;
  const cloudHosting = S.cloud_base * 12;
  const customerSuccess = customers * S.support_cust;
  const paymentFees = Billings * pct('payment_fee');
  const COGS = gpuInferenceCost + cloudHosting + customerSuccess + paymentFees;
  const GrossMargin = GAAP_Revenue - COGS;
  const GrossMarginPct = GAAP_Revenue > 0 ? (GrossMargin / GAAP_Revenue) * 100 : 0;

  // 6. OpEx
  const repPayroll = S.sales_reps * S.rep_salary * (1 + pct('charges'));
  const mktSpend = S.mkt_budget * 12;
  const SM_Expense = repPayroll + mktSpend;

  const engPayroll = S.engineers * S.eng_salary * (1 + pct('charges'));
  const RD_Expense = engPayroll;

  const gaTools = S.ga_tools * 12;
  const rent = S.office_rent * 12;
  const GA_Expense = gaTools + rent;

  const OpEx = SM_Expense + RD_Expense + GA_Expense;
  const EBITDA = GrossMargin - OpEx;

  // 7. Amortissement & Résultats
  const capexInit = S.hardware_capex;
  const DA = capexInit / S.hardware_life;
  const EBIT = EBITDA - DA;
  const interest = S.debt * pct('kd');
  const EBT = EBIT - interest;
  const t = pct('tax');
  const IS = Math.max(0, EBT) * t;
  const NetIncome = EBT - IS;

  // 8. BFR & Cash Flows SaaS
  const capex = DA;
  const AR = Billings * (S.dso / 365);
  const AP = (COGS - paymentFees + gaTools) * (S.dpo / 365);
  // BFR = AR - AP - Deferred Revenue
  const BFR = AR - AP - DeferredRevenue;
  const dBFR = BFR * (g / (1 + g));

  const CFO = NetIncome + DA - dBFR;
  const CFI = -capex;
  const repay = Math.min(S.repay, S.debt);
  const CFF = -repay;
  const FCF = CFO + CFI;

  // 9. Ratios SaaS
  const CAC = newCustYr > 0 ? SM_Expense / newCustYr : 0;
  const custGrossMarginYr = ACV * (GrossMarginPct / 100);
  const CACPaybackMonths = custGrossMarginYr > 0 ? (CAC / (custGrossMarginYr / 12)) : Infinity;
  const churnAnnual = Math.max(0.03, churnRate);
  const LTV = custGrossMarginYr / churnAnnual;
  const LTV_CAC = CAC > 0 ? LTV / CAC : 0;

  const FCF_Margin_Pct = GAAP_Revenue > 0 ? (FCF / GAAP_Revenue) * 100 : 0;
  const ARR_Growth_Pct = S.growth;
  const RuleOf40 = ARR_Growth_Pct + FCF_Margin_Pct;

  const netNewARR = ARR * g;
  const MagicNumber = SM_Expense > 0 ? netNewARR / SM_Expense : 0;

  // 10. Trésorerie & Dette nette d'ouverture
  const ar0_calc = (Billings * (S.dso / 365)) / (1 + g);
  const ap0_calc = ((COGS - paymentFees + gaTools) * (S.dpo / 365)) / (1 + g);
  const defRev0_calc = DeferredRevenue / (1 + g);
  const need0 = capexInit + ar0_calc - ap0_calc - defRev0_calc;
  const cash0 = Math.max(0, S.debt - need0);
  const netDebt = S.debt - cash0;

  // 11. Valorisation SaaS (Multiple ARR + DCF)
  let multipleAdj = S.base_multiple;
  if (RuleOf40 > 40) multipleAdj += (RuleOf40 - 40) * 0.12;
  if (NRR > 110) multipleAdj += (NRR - 110) * 0.10;
  if (GrossMarginPct > 75) multipleAdj += (GrossMarginPct - 75) * 0.08;
  const effectiveMultiple = Math.max(2.5, multipleAdj);
  const EV_Multiple = ARR * effectiveMultiple;

  const usableShield = (ebit, int, tax) => tax * (Math.max(0, ebit) - Math.max(0, ebit - int));
  const taxShield = usableShield(EBIT, interest, t);
  const taxShieldRate = interest > 0 ? taxShield / interest : 0;
  const kdAT = pct('kd') * (1 - taxShieldRate);
  const ku = pct('rf') + S.beta * pct('mrp') + pct('size');
  const gT = pct('gTerm');
  const A_coeff = (1 - taxShieldRate) * S.beta * pct('mrp') + kdAT;

  const FCFF = (EBIT - Math.max(0, EBIT) * t) + DA - capex - dBFR;
  const EV_DCF_raw = (ku > gT && FCFF > 0) ? (FCFF + netDebt * (ku - A_coeff)) / (ku - gT) : 0;
  const EV_DCF = Math.max(0, EV_DCF_raw);

  const EV = Math.max(0, EV_Multiple);
  const EquityValue = Math.max(0, EV - netDebt);
  const investedInitial = capexInit + BFR / (1 + g);
  const ProjectNPV = EV - investedInitial;

  const hasCap = EV > netDebt && netDebt >= 0;
  const dv = hasCap && EV > 0 ? netDebt / EV : 0;
  const betaL = hasCap && EquityValue > 0 ? S.beta * (1 + (1 - taxShieldRate) * netDebt / EquityValue) : S.beta;
  const ke = pct('rf') + betaL * pct('mrp') + pct('size');
  const WACC = (1 - dv) * ke + dv * kdAT;

  return {
    maxDemosMo, leadsMo, servedRatio, actualDemosMo, lostLeadsMo, newCustMo, newCustYr, customers,
    ACV, ARR, MRR, GAAP_Revenue, Billings, DeferredRevenue,
    GRR, NRR, churnRate, expRate,
    gpuInferenceCost, cloudHosting, customerSuccess, paymentFees, COGS, GrossMargin, GrossMarginPct,
    repPayroll, mktSpend, SM_Expense, engPayroll, RD_Expense, gaTools, rent, GA_Expense, OpEx,
    EBITDA, DA, EBIT, interest, EBT, IS, Tax: IS, NetIncome,
    capexInit, capex, AR, AP, BFR, dBFR, CFO, CFI, CFF, FCF, FCFF, repay,
    cash0, netDebt,
    CAC, CACPaybackMonths, LTV, LTV_CAC, RuleOf40, FCF_Margin_Pct, ARR_Growth_Pct, MagicNumber,
    effectiveMultiple, EV_Multiple, EV_DCF, EV, EquityValue, ProjectNPV,
    ku, dv, betaL, ke, kdAT, WACC, gT, taxShield, taxShieldRate, investedInitial
  };
}

function saasBalanceSheet(S, R) {
  const g = S.growth / 100;
  const ar0 = R.AR / (1 + g);
  const ap0 = R.AP / (1 + g);
  const defRev0 = R.DeferredRevenue / (1 + g);

  const need = R.capexInit + ar0 - ap0 - defRev0;
  const cash0 = R.cash0;
  const eq0 = Math.max(0, need - S.debt);

  const netClosingCash = cash0 + R.CFO + R.CFI + R.CFF;
  const cashClosingAsset = Math.max(0, netClosingCash);
  const overdraftClosing = Math.max(0, -netClosingCash);

  const v = {
    immo: [R.capexInit, R.capexInit + R.capex - R.DA],
    ar: [ar0, R.AR],
    cash: [cash0, cashClosingAsset],
    overdraft: [0, overdraftClosing],
    debt: [S.debt, S.debt - R.repay],
    ap: [ap0, R.AP],
    defRev: [defRev0, R.DeferredRevenue]
  };

  const ta = [0, 1].map(i => v.immo[i] + v.ar[i] + v.cash[i]);
  const eq = [eq0, eq0 + R.NetIncome];
  const tp = [0, 1].map(i => eq[i] + v.debt[i] + v.overdraft[i] + v.ap[i] + v.defRev[i]);

  return { v, ta, tp, eq, cash0, netClosingCash };
}

